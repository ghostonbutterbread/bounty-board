class CliError(ValueError):
    pass


class ClaudeAdapter:
    """Claude Code in a report sandbox, talking to the model relay."""
    rule = terminal_relay.CLAUDE_RULE

    def argv(self, binary, model):
        args = [binary]
        if model != 'default':
            args += ['--model', model]
        # --mcp-config takes several values, so the prompt goes after "--".
        return args + CLAUDE_FIXED_ARGS + ['--', INITIAL_PROMPT]

    def managed_settings(self):
        """``/etc/claude-code/managed-settings.json``: generated by the host, mounted read-only.

        Verified with Claude Code 2.1.331 in the sandbox (a host-owned file on a
        read-only bind counts): the managed ``ask`` rule ("Rule Bash from
        enterprise managed settings says to ask") wins over ``allow: ["Bash"]``
        in user settings, in a settings file the agent rewrote itself, in project
        settings, and over a loaded skill's ``allowed-tools: [Bash]``.
        ``allowManagedPermissionRulesOnly`` makes Claude Code ignore every lower
        permission rule and the ``allowed-tools`` frontmatter of user and project
        skills; hooks and MCP servers are limited to managed ones (none).
        """
        return {
            'permissions': {
                'ask': list(CLAUDE_ALWAYS_ASK),
                'deny': list(CLAUDE_MANAGED_DENY),
                'allow': list(CLAUDE_MANAGED_ALLOW),
                'defaultMode': 'acceptEdits',
                'additionalDirectories': [AGENT_DIR],
                'disableAutoMode': 'disable',
                'disableBypassPermissionsMode': 'disable',
            },
            'allowManagedPermissionRulesOnly': True,
            'allowManagedHooksOnly': True,
            'disableAllHooks': True,
            'allowManagedMcpServersOnly': True,
            'allowedMcpServers': [],
            'enableAllProjectMcpServers': False,
            'disableSkillShellExecution': True,
            'env': self.quiet_env(),
        }

    def quiet_env(self):
        return {key: value for key, value in self.env().items() if key.startswith(('DISABLE_', 'CLAUDE_CODE_DISABLE'))}

    def env(self):
        return {
            'ANTHROPIC_BASE_URL': f'http://127.0.0.1:{RELAY_PORT}',
            'CLAUDE_CODE_OAUTH_TOKEN': DUMMY_OAUTH_TOKEN,
            'DISABLE_AUTOUPDATER': '1',
            'CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC': '1',
            'CLAUDE_CODE_DISABLE_OFFICIAL_MARKETPLACE_AUTOINSTALL': '1',
            'DISABLE_TELEMETRY': '1',
            'DISABLE_ERROR_REPORTING': '1',
        }

    def home_files(self, skills, version=None):
        """Files for the tmpfs HOME: {relative path: bytes} and {relative path: symlink target}.

        Keys discovered with Claude Code 2.1.331 against a fake upstream (see
        docs/integrations/report-agent.md, Evidence): onboarding done, /report
        trusted, the auto-mode offer seen, no marketplace auto-install (it
        would fetch from downloads.claude.ai). The permission policy is not
        here: it lives in ``managed_settings`` (read-only), because HOME is
        writable from the sandbox.
        """
        state = {
            'hasCompletedOnboarding': True,
            'hasSeenAutoDefaultNudge': True,
            'theme': 'dark',
            'autoUpdates': False,
            'officialMarketplaceAutoInstallAttempted': True,
            'officialMarketplaceAutoInstalled': False,
            'officialMarketplaceAutoInstallFailReason': 'policy_blocked',
            'projects': {'/report': {'hasTrustDialogAccepted': True, 'hasCompletedProjectOnboarding': True,
                                     'allowedTools': []}},
        }
        if version:
            state['lastOnboardingVersion'] = version
        settings = {'env': self.quiet_env()}  # convenience only; the managed file holds the policy
        files = {
            '.claude.json': json.dumps(state, indent=2).encode() + b'\n',
            '.claude/settings.json': json.dumps(settings, indent=2).encode() + b'\n',
        }
        # Docker would create a bind target's parents root-owned inside the tmpfs
        # HOME, and Claude Code must write ~/.claude, so the one skills tree is mounted
        # at SKILLS_DIR and ~/.claude/skills is a single link to it (Claude Code follows it).
        links = {'.claude/skills': SKILLS_DIR} if skills else {}
        return files, links


class CliSpec:
    def __init__(self, cli_id, label, models, *, default_model='default', custom_models=False, adapter=None,
                 reason=None):
        self.id, self.label = cli_id, label
        self.models = tuple(models)
        self.default_model = default_model
        self.custom_models = custom_models
        self.adapter = adapter
        self.reason = reason if adapter is None else None

    @property
    def sandbox_ready(self):
        return self.adapter is not None

    def valid_model(self, model):
        if not isinstance(model, str):
            return False
        return model in self.models or (self.custom_models and MODEL_RE.fullmatch(model) is not None)


REGISTRY = {spec.id: spec for spec in (
    CliSpec('claude', 'Claude Code', ('default', 'opus', 'sonnet', 'haiku'), custom_models=True,
            adapter=ClaudeAdapter()),
    CliSpec('codex', 'Codex', ('default',), reason='needs_sandbox_login'),
    CliSpec('omp', 'OMP', ('default',), reason='needs_sandbox_login'),
    CliSpec('opencode', 'OpenCode', ('default',), reason='needs_sandbox_login'),
)}
