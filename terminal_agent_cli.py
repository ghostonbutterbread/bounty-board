def parse_pair(value, what, name_re):
    """'NAME=PATH' from a repeatable flag."""
    name, sep, path = value.partition('=')
    if not sep or not name_re.fullmatch(name) or not path or not os.path.isabs(path):
        raise CliError(f'{what} must look like NAME=/absolute/path: {value}')
    return name, path


def parse_cli_flags(values):
    """``--report-agent-cli ID=PATH`` values -> {id: path}; ids must be in REGISTRY."""
    out = {}
    for value in values:
        cli_id, path = parse_pair(value, '--report-agent-cli', CLI_ID_RE)
        if cli_id not in REGISTRY:
            raise CliError(f'unknown CLI id {cli_id!r} (known: {", ".join(sorted(REGISTRY))})')
        if cli_id in out:
            raise CliError(f'--report-agent-cli {cli_id} given twice')
        out[cli_id] = path
    return out


def parse_skill_flags(values):
    """``--report-agent-skill NAME=PATH`` -> {name: path}. Symlinked skill directories are refused."""
    out = {}
    for value in values:
        name, path = parse_pair(value, '--report-agent-skill', SKILL_NAME_RE)
        if name in out:
            raise CliError(f'--report-agent-skill {name} given twice')
        check_skill_dir(path)
        if re.search(r'[,"\x00-\x1f]', path):
            raise CliError(f'skill path cannot contain a comma, quote or control character: {name}')
        out[name] = path
    return out


def check_skill_dir(path):
    try:
        info = os.lstat(path)
    except OSError as error:
        raise CliError(f'skill directory {path}: {error.strerror}') from None
    if stat.S_ISLNK(info.st_mode):
        raise CliError(f'skill directory {path} is a symlink (refused)')
    if not stat.S_ISDIR(info.st_mode):
        raise CliError(f'skill directory {path} is not a directory')
    return info


def resolve_binary(path):
    """Resolve symlinks on the host; the result must be an executable regular file
    whose path Docker's --mount syntax can carry. Returns the real path or raises CliError."""
    if not path:
        raise CliError('not configured')
    real = os.path.realpath(path)
    try:
        info = os.stat(real)
    except OSError:
        raise CliError('binary not found') from None
    if not stat.S_ISREG(info.st_mode) or not os.access(real, os.X_OK):
        raise CliError('binary is not an executable file')
    if re.search(r'[,"\x00-\x1f]', real):
        raise CliError('binary path contains a comma, quote or control character')
    return real


# -- skills: read-only copies without permission-widening frontmatter ---------------------

# A skill's frontmatter can widen what runs without asking (allowed-tools pre-approves tools while
# the skill is loaded; hooks and MCP servers run code). Copies keep only name and description.
SKILL_COPY_MAX = 64 * 1024 * 1024
SKILL_FILES_MAX = 2000
# The whole generated tree (every skill of --report-agent-skills-dir plus --report-agent-skill).
TREE_MAX_BYTES = 256 * 1024 * 1024
TREE_MAX_FILES = 20000


def check_skills_dir(path):
    """``--report-agent-skills-dir``: a real directory (not a symlink) owned by this user and not
    writable by others. Group-writable is accepted (Hoster's umask 002). Raises CliError."""
    try:
        info = os.lstat(path)
    except OSError as error:
        raise CliError(f'skills directory {path}: {error.strerror}') from None
    if stat.S_ISLNK(info.st_mode):
        raise CliError(f'skills directory {path} is a symlink (refused)')
    if not stat.S_ISDIR(info.st_mode):
        raise CliError(f'skills directory {path} is not a directory')
    if info.st_uid != os.getuid():
        raise CliError(f'skills directory {path} is owned by another user')
    if info.st_mode & 0o002:
        raise CliError(f'skills directory {path} is writable by other users')
    return info


def _inside(path, real_root):
    return path == real_root or path.startswith(real_root.rstrip('/') + '/')


def discover_skills(skills_dir, root, log, identities=None):
    """{name: real source directory} for every top-level entry of ``skills_dir`` that is a
    directory, or a symlink to one, with a top-level regular SKILL.md. A top-level symlink is
    resolved once; its target must be a directory owned by this user and outside ``root``.
    Everything else is skipped with one log line (names and reasons only, never contents)."""
    try:
        check_skills_dir(skills_dir)
        names = sorted(os.listdir(skills_dir))
    except (CliError, OSError) as error:
        log(f'skills dir not used: {error}')
        return {}
    real_root = os.path.realpath(str(root))
    out, skipped = {}, 0
    for name in names:
        full = os.path.join(skills_dir, name)

        def skip(reason):
            nonlocal skipped
            skipped += 1
            log(f'skills dir: skipped {name!r}: {reason}')
        if not SKILL_NAME_RE.fullmatch(name):
            skip('name not allowed')
            continue
        try:
            info = os.lstat(full)
            target = os.path.realpath(full) if stat.S_ISLNK(info.st_mode) else full
            target_info = os.lstat(target)
        except OSError:
            skip('broken link')
            continue
        if not stat.S_ISDIR(target_info.st_mode):
            skip('not a directory')
            continue
        if target_info.st_uid != os.getuid():
            skip('owned by another user')
            continue
        if _inside(os.path.realpath(target), real_root):
            skip('inside the Board data root')
            continue
        try:
            if not stat.S_ISREG(os.lstat(os.path.join(target, 'SKILL.md')).st_mode):
                raise OSError
        except OSError:
            skip('no top-level SKILL.md')
            continue
        out[name] = target
        if identities is not None:
            identities[name] = (target_info.st_dev, target_info.st_ino)   # copy_skill re-checks this
    log(f'skills dir: {len(out)} skills found, {skipped} skipped')
    return out


def strip_frontmatter(text):
    """SKILL.md text whose YAML frontmatter is rewritten to only ``name`` and ``description``
    (quoted), so no spelling of ``allowed-tools``, hooks or MCP servers (quoted or explicit
    keys, a BOM, block scalars) survives in the copy. The body is kept byte for byte.

    No frontmatter: returned as is (minus a leading BOM). A frontmatter block that does not
    close, or a name/description this reader cannot parse, raises CliError and the skill is
    skipped rather than mounted with keys it could not check (review r2 N1).
    """
    text = text.lstrip('\ufeff')
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].rstrip('\r\n') != '---':
        return text
    close = next((i for i in range(1, len(lines)) if lines[i].rstrip('\r\n') == '---'), None)
    if close is None:
        raise CliError('skill frontmatter has no closing ---')
    fields, index = {}, 1
    while index < close:
        line = lines[index].rstrip('\r\n')
        index += 1
        match = re.match(r'(name|description)[ \t]*:(.*)$', line)
        if not match:
            continue
        key, value = match.group(1), match.group(2).strip()
        if key in fields:
            raise CliError(f'skill frontmatter repeats {key}')
        if re.fullmatch(r'[|>][+-]?[0-9]?', value):
            block = []
            while index < close and (not lines[index].strip() or lines[index][:1] in ' \t'):
                block.append(lines[index].strip())
                index += 1
            value = ('\n' if value[0] == '|' else ' ').join(part for part in block).strip()
        elif value.startswith('"'):
            try:
                value = json.loads(value)
            except ValueError:
                raise CliError(f'skill frontmatter {key} is not a simple quoted string') from None
        elif value.startswith("'"):
            if len(value) < 2 or not value.endswith("'"):
                raise CliError(f'skill frontmatter {key} is not a simple quoted string')
            value = value[1:-1].replace("''", "'")
        if not isinstance(value, str):
            raise CliError(f'skill frontmatter {key} is not a string')
        fields[key] = value
    head = ['---\n'] + [f'{key}: {json.dumps(fields[key])}\n' for key in ('name', 'description') if key in fields]
    return ''.join(head) + '---\n' + ''.join(lines[close + 1:])


# Never copied into the tree, at any depth (review rv2 V1): version-control metadata (a worktree's
# .git is a file naming a host path) and every other dot-directory. On Ghost's 208 skills the only
# dot-directories were .git (409 files, 1 skill) and .pytest_cache (4 files, 1 skill); no skill needs one.
VCS_NAMES = frozenset({'.git', '.hg', '.svn', '.bzr', 'CVS'})


def skipped_entry(name, mode):
    """True for an entry the tree never holds: VCS metadata (file or folder) or a dot-directory."""
    return name in VCS_NAMES or (stat.S_ISDIR(mode) and name.startswith('.'))


def skill_signature(path):
    """What a copy depends on: every kept entry's relative path, type, mode, link count, size and
    mtime (symlinks not followed; VCS metadata and dot-directories left out, as in copy_skill)."""
    entries = []
    for folder, dirs, files in os.walk(path, followlinks=False):
        kept = []
        for name in sorted(dirs + files):
            full = os.path.join(folder, name)
            info = os.lstat(full)
            if skipped_entry(name, info.st_mode):
                continue
            if name in dirs:
                kept.append(name)
            entries.append((os.path.relpath(full, path), info.st_mode, info.st_nlink, info.st_size, info.st_mtime_ns))
        dirs[:] = [d for d in dirs if d in kept]
    info = os.lstat(path)
    return repr((info.st_ino, info.st_mtime_ns, entries))


def copy_skill(src, dest, expect=None, log=None):
    """Copy a skill folder into ``dest`` (new) and return (bytes, files) copied.

    Walked from a directory handle opened with O_NOFOLLOW|O_DIRECTORY whose device and inode must
    equal ``expect`` (what discovery checked), with every open below it relative to its parent's
    handle, so a folder swapped for a symlink after the checks is refused (review rv2 V6). Kept:
    regular files and folders. Skipped: symlinks, FIFOs, sockets and devices (lstat first, then a
    non-blocking open and an fstat check, so nothing can block: rv2 V2), VCS metadata and
    dot-directories (rv2 V1), and files with more than one link or not readable by others (rv2 V6;
    one log line each, the relative name only). SKILL.md files are stripped; dirs 0755, files 0644;
    size and count capped."""
    say = log or (lambda message: None)
    skill = os.path.basename(src)
    try:
        root_fd = os.open(src, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    except OSError:
        raise CliError(f'skill {skill}: the folder could not be opened (a symlink or gone)') from None
    totals = [0, 0]
    try:
        info = os.fstat(root_fd)
        if expect is not None and (info.st_dev, info.st_ino) != tuple(expect):
            raise CliError(f'skill {skill}: the folder changed after it was checked')
        os.mkdir(dest, 0o755)
        _copy_dir(root_fd, dest, '', skill, totals, say)
    finally:
        os.close(root_fd)
    return totals[0], totals[1]


def _copy_dir(dir_fd, dest, rel, skill, totals, say):
    for name in sorted(os.listdir(dir_fd)):
        path = f'{rel}{name}'
        try:
            info = os.stat(name, dir_fd=dir_fd, follow_symlinks=False)
        except OSError:
            continue
        if skipped_entry(name, info.st_mode):
            continue
        if stat.S_ISDIR(info.st_mode):
            try:
                sub = os.open(name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=dir_fd)
            except OSError:
                continue
            try:
                again = os.fstat(sub)
                if (again.st_dev, again.st_ino) != (info.st_dev, info.st_ino):
                    continue
                os.mkdir(os.path.join(dest, name), 0o755)
                _copy_dir(sub, os.path.join(dest, name), path + '/', skill, totals, say)
            finally:
                os.close(sub)
            continue
        if not stat.S_ISREG(info.st_mode):
            continue  # symlink, FIFO, socket or device: never opened
        if info.st_nlink > 1:
            say(f'skill {skill!r}: skipped {path!r}: more than one hard link')
            continue
        if not info.st_mode & 0o004:
            say(f'skill {skill!r}: skipped {path!r}: not readable by others')
            continue
        try:
            fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=dir_fd)
        except OSError:
            continue
        with os.fdopen(fd, 'rb') as stream:
            got = os.fstat(fd)
            if (not stat.S_ISREG(got.st_mode) or (got.st_dev, got.st_ino) != (info.st_dev, info.st_ino)
                    or got.st_nlink > 1 or not got.st_mode & 0o004):
                continue
            data = stream.read(SKILL_COPY_MAX + 1)
        totals[0] += len(data)
        totals[1] += 1
        if totals[0] > SKILL_COPY_MAX or totals[1] > SKILL_FILES_MAX:
            raise CliError(f'skill {skill} is too large to copy')
        if name == 'SKILL.md':
            try:
                data = strip_frontmatter(data.decode('utf-8')).encode('utf-8')
            except UnicodeError:
                raise CliError(f'skill {skill} has a SKILL.md that is not UTF-8') from None
        out = os.open(os.path.join(dest, name), os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644)
        with os.fdopen(out, 'wb') as stream:
            stream.write(data)
